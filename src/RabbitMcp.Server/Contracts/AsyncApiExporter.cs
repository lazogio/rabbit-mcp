using System.Text.Json.Nodes;
using RabbitMcp.Server.Messaging;

namespace RabbitMcp.Server.Contracts;

/// <summary>
/// Describes contracts as an AsyncAPI 3.0 document: one channel and one send operation per contract (with a reply for
/// requests), AMQP bindings for exchange/queue and routing key, and the wire JSON Schema of every message — readable by
/// AsyncAPI tooling and by <see cref="AsyncApiLoader"/> (the round trip keeps names, routing, format and types).
/// </summary>
public static class AsyncApiExporter
{
    public static JsonObject Export(ContractRegistry registry, string title, string version = "1.0.0")
    {
        var channels = new JsonObject();
        var operations = new JsonObject();
        var messages = new JsonObject();

        foreach (var c in registry.Contracts)
        {
            var message = Message(c.Name, c.MessageTypeUrn, c.Description, c.IsRaw, ContractDiff.SchemaOf(c), c.Version);
            if (c.ToolName != (c.IsRequest ? "request_" : "publish_") + ContractRegistry.ToSnakeCase(c.Name))
                ((JsonObject)message[AsyncApiLoader.Extension]!)["toolName"] = c.ToolName;
            messages[c.Name] = message;
            foreach (var r in c.Responses.Where(r => !messages.ContainsKey(r.Name)))
                messages[r.Name] = Message(r.Name, r.MessageTypeUrn, $"Reply to {c.Name}.", c.IsRaw, ContractDiff.SchemaOf(r), null);

            var channelMessages = new JsonObject { [c.Name] = Ref($"#/components/messages/{c.Name}") };
            foreach (var r in c.Responses)
                channelMessages[r.Name] = Ref($"#/components/messages/{r.Name}");

            channels[c.Name] = new JsonObject
            {
                ["address"] = c.RoutingKey.Length > 0 ? c.RoutingKey : null, // the routing key; none for fanout exchanges
                ["messages"] = channelMessages,
                ["bindings"] = new JsonObject
                {
                    ["amqp"] = c.UsesDefaultExchange
                        ? new JsonObject { ["is"] = "queue", ["queue"] = new JsonObject { ["name"] = c.RoutingKey } }
                        : new JsonObject
                        {
                            ["is"] = "routingKey",
                            ["exchange"] = c.IsRaw
                                ? new JsonObject { ["name"] = c.Exchange }
                                : new JsonObject { ["name"] = c.Exchange, ["type"] = "fanout" },
                        },
                },
            };

            var operation = new JsonObject
            {
                ["action"] = "send",
                ["channel"] = Ref($"#/channels/{c.Name}"),
                ["messages"] = new JsonArray(Ref($"#/channels/{c.Name}/messages/{c.Name}")),
            };
            if (c.IsRequest)
            {
                operation["reply"] = new JsonObject
                {
                    ["messages"] = new JsonArray([.. c.Responses.Select(r => (JsonNode)Ref($"#/channels/{c.Name}/messages/{r.Name}"))]),
                };
            }
            operations[ContractRegistry.ToSnakeCase(c.Name)] = operation;
        }

        return new JsonObject
        {
            ["asyncapi"] = "3.0.0",
            ["info"] = new JsonObject
            {
                ["title"] = title,
                ["version"] = version,
                ["description"] = "Generated by rabbit-mcp from its message contracts.",
            },
            ["channels"] = channels,
            ["operations"] = operations,
            ["components"] = new JsonObject { ["messages"] = messages },
        };
    }

    private static JsonObject Message(string name, string urn, string description, bool raw, JsonNode schema, int? version)
    {
        var extension = new JsonObject { ["format"] = raw ? "raw" : "masstransit", ["urn"] = urn };
        if (version is { } v)
            extension["version"] = v;
        return new JsonObject
        {
            ["name"] = name,
            ["title"] = name,
            ["summary"] = description,
            ["contentType"] = raw ? RawMessages.ContentType : MassTransitJson.ContentType,
            ["payload"] = schema,
            [AsyncApiLoader.Extension] = extension,
        };
    }

    private static JsonObject Ref(string reference) => new() { ["$ref"] = reference };
}
